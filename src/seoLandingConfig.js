export const SEO_LANDING_URLS = SEO_LANDING_PAGES.map((page) => `https://www.khanhouse.co.kr/${page.slug}`);

export function getSeoLanding(slug) {
  return SEO_LANDING_PAGES.find((page) => page.slug === slug) || null;
}

function normalized(value) {
  return String(value ?? '').replace(/\s+/gu, ' ').trim();
}

export function matchesSeoLanding(page, property) {
  if (!page || !property) return false;
  if (property.status !== 'published' || property.availability_status !== 'active'
    || property.review_state !== 'approved' || property.ad_visibility !== '공개') return false;
  const address = normalized(property.address);
  if (/칠곡군|김천시|포항시|대구광역시/u.test(address)) return false;
  const category = [property.category, property.property_type].map(normalized).join(' ');
  const trade = normalized(property.trade_type);
  if (page.districts && !page.districts.some((district) => address.split(/[\s(),]+/u).includes(district))) return false;
  if (page.monthlyOnly && !/월세/u.test(trade)) return false;
  const sale = /매매/u.test(trade);
  if (page.mode === 'building-sale') {
    return sale && /원룸건물|다가구|수익형/u.test([category, property.title].join(' '));
  }
  if (sale) return false;
  if (page.mode === 'one-room') {
    return /원룸/u.test(category) && !/미니|미투|투룸|원룸건물|다가구/u.test(category);
  }
  if (page.mode === 'mini-room') {
    return /미니투룸|미투/u.test(category);
  }
  if (page.mode === 'jinpyeong-mini') {
    return address.includes('진평동') && /미니투룸|미투/u.test(category);
  }
  if (page.mode === 'two-room') {
    return /투룸/u.test(category) && !/미니투룸|미투|쓰리룸|원룸건물/u.test(category);
  }
  return false;
}

export function selectSeoLandingProperties(page, properties, limit = 12) {
  return (Array.isArray(properties) ? properties : [])
    .filter((item) => matchesSeoLanding(page, item))
    .sort((a, b) => String(b.updated_at || '').localeCompare(String(a.updated_at || '')))
    .slice(0, limit);
}

import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

const db = new PGlite();
await db.exec(`
  create schema auth;
  create table auth.users(id uuid primary key default gen_random_uuid());
  create role anon; create role authenticated; create role service_role;
  create table public.properties(
    id uuid primary key default gen_random_uuid(), listing_number bigint generated by default as identity unique,
    title text not null, category text default '', property_type text default '', trade_type text default '',
    address text default '', real_unit text default '', deposit text default '', rent text default '', maintenance_fee text default '',
    photos jsonb default '[]'::jsonb, image_count integer default 0, area text default '', floor_info text default '',
    direction text default '', parking text default '', move_in text default '', approval_date text default '', legal_notice text default '',
    summary text default '', description text default '', owner_phone text default '', entrance_password text default '', private_memo text default '', client_info text default '', status text default 'pending', ad_visibility text default '비공개',
    created_by_role text default '', created_by text default '', updated_by text default '', updated_at timestamptz default now()
  );
`);

for (const file of [
  'supabase/migrations/20260808170000_gumi_vacancy_import.sql',
  'supabase/migrations/20260808190000_ai_consultation.sql'
]) {
  await db.exec(await readFile(file, 'utf8'));
}

const user = await db.query(`insert into auth.users default values returning id`);
const userId = user.rows[0].id;
const batch = await db.query(`select (public.gumi_create_import_batch($1::uuid)).id`, [userId]);
const batchId = batch.rows[0].id;
const records = [{ address: '인의동 669-8', normalizedAddress: '인의동 669-8', unit: '301', sourcePropertyType: '미니투룸', depositAmount: 300, rentAmount: 30, managementFeeAmount: 8, sourceRegisteredAt: '2026-08-01', sourceIntSeq: 10, canonicalIdentity: '인의동 669-8|301|미니투룸', disposition: 'ready', errors: [] }];
await db.query(`select public.gumi_import_chunk($1::uuid,$2::jsonb)`, [batchId, JSON.stringify(records)]);
const publicQuick = await db.query(`select id,listing_number,listing_type,status,ad_visibility,review_state,availability_status from public.properties`);
assert.equal(publicQuick.rows[0].listing_type, 'quick');
assert.equal(publicQuick.rows[0].status, 'pending');
assert.equal(publicQuick.rows[0].ad_visibility, '비공개');
const rejectedApproval = await db.query(`select public.gumi_approve_quick_property($1) result`, [publicQuick.rows[0].id]);
assert.equal(rejectedApproval.rows[0].result.ok, false);
assert(rejectedApproval.rows[0].result.missingFields.includes('area'));
await db.query(`update public.properties set area='20㎡', floor_info='3층', direction='남향', parking='가능', move_in='즉시', approval_date='2020-01-01', legal_notice='중개대상물 표시정보 확인', owner_phone='010-9999-9999', entrance_password='secret', private_memo='private' where id=$1`, [publicQuick.rows[0].id]);
const approvedQuick = await db.query(`select public.gumi_approve_quick_property($1) result`, [publicQuick.rows[0].id]);
assert.equal(approvedQuick.rows[0].result.ok, true);
const publishedQuick = await db.query(`select status,ad_visibility,review_state,jsonb_array_length(photos) photo_count from public.properties where id=$1`, [publicQuick.rows[0].id]);
assert.equal(publishedQuick.rows[0].status, 'published');
assert.equal(publishedQuick.rows[0].photo_count, 0);

records[0].sourceIntSeq = 11; records[0].depositAmount = 400; records[0].rentAmount = 28;
await db.query(`select public.gumi_import_chunk($1::uuid,$2::jsonb)`, [batchId, JSON.stringify(records)]);
const identityCheck = await db.query(`select count(*)::int count from public.properties`);
assert.equal(identityCheck.rows[0].count, 1);
const idHistory = await db.query(`select count(*)::int count from public.property_source_ids`);
assert.equal(idHistory.rows[0].count, 2);
await db.query(`select public.gumi_finalize_import_batch($1::uuid,$2::uuid,false,null)`, [batchId, userId]);

const emptyBatch = await db.query(`select (public.gumi_create_import_batch($1::uuid)).id`, [userId]);
const other = [{ ...records[0], address: '진평동 1-1', normalizedAddress: '진평동 1-1', unit: '101', sourceIntSeq: 12, canonicalIdentity: '진평동 1-1|101|미니투룸' }];
await db.query(`select public.gumi_import_chunk($1::uuid,$2::jsonb)`, [emptyBatch.rows[0].id, JSON.stringify(other)]);
await assert.rejects(() => db.query(`select public.gumi_finalize_import_batch($1::uuid,$2::uuid,false,null)`, [emptyBatch.rows[0].id, userId]), /strong confirmation required/u);
await db.query(`select public.gumi_finalize_import_batch($1::uuid,$2::uuid,true,'전체 가져오기 완료')`, [emptyBatch.rows[0].id, userId]);
const missing = await db.query(`select availability_status from public.properties where address='인의동 669-8'`);
assert.equal(missing.rows[0].availability_status, 'missing');

const reappearBatch = await db.query(`select (public.gumi_create_import_batch($1::uuid)).id`, [userId]);
await db.query(`select public.gumi_import_chunk($1::uuid,$2::jsonb)`, [reappearBatch.rows[0].id, JSON.stringify(records)]);
const active = await db.query(`select availability_status from public.properties where address='인의동 669-8'`);
assert.equal(active.rows[0].availability_status, 'active');

const search = await db.query(`select id,listing_type from public.ai_search_public_properties('인의동','미니투룸',500,30,10,5,false)`);
assert.equal(search.rows.length, 1);
assert.equal(Object.hasOwn(search.rows[0], 'owner_phone'), false);

const conversation = await db.query(`insert into public.ai_conversations(access_token_hash,context) values ('hash','{}') returning id`);
const recommendation = await db.query(`insert into public.ai_recommendations(conversation_id,recommendation_number,property_id,snapshot) values ($1,2,$2,$3::jsonb) returning id`, [conversation.rows[0].id, publicQuick.rows[0].id, JSON.stringify({ recommendationNumber: 2, propertyId: publicQuick.rows[0].id })]);
const viewing = await db.query(`insert into public.viewing_requests(conversation_id,property_id,recommendation_id,customer_name,customer_phone,desired_date,desired_time,consultation_summary) values ($1,$2,$3,'홍길동','01012345678','2026-08-10','18:00','AI 상담 요약') returning id,staff_status`, [conversation.rows[0].id, publicQuick.rows[0].id, recommendation.rows[0].id]);
assert.equal(viewing.rows[0].staff_status, 'new');
const fixed = await db.query(`select property_id from public.ai_recommendations where conversation_id=$1 and recommendation_number=2`, [conversation.rows[0].id]);
assert.equal(fixed.rows[0].property_id, publicQuick.rows[0].id);

await db.close();
console.log('transaction migration and DB integration tests: ok');
